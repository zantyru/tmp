# Пример функции, возвращающей значение
# и принимающей два аргумента (параметра)


# Функция, вычисляющая площадь прямоугольника.
# Она вычисляет и возвращает результат. Это мы
# её так написали
def calculate_area(a, b):

    return a * b


# Функция, вычисляющая площадь прямоугольника,
# которая не возвращает результат, а просто
# печатает его
def print_area(a, b):

    print(a * b)


x = calculate_area(10, 3)
print(f"{x = }")

y = print_area(10, 3)  # :^(
print(f"{y = }")
